def bit_operations(x, i):
    print("=" * 50)
    print(f"Number: {x}")
    print(f"Binary: {bin(x)}")
    print()

    # ----------------------------------------------------
    # 1. Check ith bit
    # ----------------------------------------------------
    print(f"Check bit {i}:",
          "SET" if x & (1 << i) else "NOT SET")

    # ----------------------------------------------------
    # 2. Set ith bit
    # ----------------------------------------------------
    print(f"Set bit {i}:",
          bin(x | (1 << i)),
          x | (1 << i))

    # ----------------------------------------------------
    # 3. Clear ith bit
    # ----------------------------------------------------
    print(f"Clear bit {i}:",
          bin(x & ~(1 << i)),
          x & ~(1 << i))

    # ----------------------------------------------------
    # 4. Toggle ith bit
    # ----------------------------------------------------
    print(f"Toggle bit {i}:",
          bin(x ^ (1 << i)),
          x ^ (1 << i))

    # ----------------------------------------------------
    # 5. Even / Odd
    # ----------------------------------------------------
    print("Even" if x % 2 == 0 else "Odd")

    # ----------------------------------------------------
    # 6. Left Shift
    # ----------------------------------------------------
    print("Left Shift (x << 1):", x << 1)

    # ----------------------------------------------------
    # 7. Right Shift
    # ----------------------------------------------------
    print("Right Shift (x >> 1):", x >> 1)

    # ----------------------------------------------------
    # 8. Count Set Bits
    # ----------------------------------------------------
    print("Set Bits:", x.bit_count())

    # ----------------------------------------------------
    # 9. Power of Two
    # ----------------------------------------------------
    print("Power of Two:",
          x > 0 and (x & (x - 1)) == 0)

    # ----------------------------------------------------
    # 10. Remove Lowest Set Bit
    # ----------------------------------------------------
    print("Remove Lowest Set Bit:",
          bin(x & (x - 1)),
          x & (x - 1))

    # ----------------------------------------------------
    # 11. Extract Lowest Set Bit
    # ----------------------------------------------------
    print("Lowest Set Bit:",
          bin(x & -x),
          x & -x)

    # ----------------------------------------------------
    # 12. Binary without 0b
    # ----------------------------------------------------
    print("Binary:", format(x, 'b'))

    # ----------------------------------------------------
    # 13. Binary (8 bits)
    # ----------------------------------------------------
    print("8-bit Binary:", format(x, '08b'))

    print("=" * 50)


# ---------------- Example ----------------

bit_operations(13, 2)


# ==========================================================
# XOR Trick 1 : Single Number
# Every number appears twice except one
# ==========================================================

nums = [2, 3, 2, 4, 4]

ans = 0
for num in nums:
    ans ^= num

print("Single Number:", ans)


# ==========================================================
# XOR Trick 2 : Missing Number
# Numbers are 0...n
# ==========================================================

nums = [3, 0, 1]

missing = len(nums)

for i in range(len(nums)):
    missing ^= i
    missing ^= nums[i]

print("Missing Number:", missing)


# ==========================================================
# Bit Masking : Generate All Subsets  
# only used when n <= 20 
# ==========================================================

nums = [1, 2, 3]
n = len(nums)

print("\nAll Subsets:")

for mask in range(1 << n):
    subset = []

    for i in range(n):
        if mask & (1 << i):
            subset.append(nums[i])

    print(subset)